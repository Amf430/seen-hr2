/* ═══════════════════════════════════════════════════════════════════════════
   صياغة النصّ الظاهر — العدّ العربي، والتحية، والأحرف الأولى

   هذه كلها نصوص يقرأها المستخدم مباشرةً. «٣ موظف في 2 أقسام» عربية مكسورة
   تُقرأ ترجمةً آلية، و«صباح الخير» في الثالثة عصراً خطأ صريح.
   ═══════════════════════════════════════════════════════════════════════════ */

import { plural, greeting, firstName, initials, hueOf, fmtDayDate } from '../js/lib/format.js';

let pass = 0, fail = 0;
const eq = (name, expected, actual) => {
  const a = JSON.stringify(actual), e = JSON.stringify(expected);
  const ok = a === e;
  ok ? pass++ : fail++;
  console.log(`  ${ok ? '\x1b[32m✓\x1b[0m' : '\x1b[31m✗\x1b[0m'} ${name}` +
    (ok ? '' : `\n      توقّعنا ${e}\n      وجاء   ${a}`));
};
const ok = (name, cond) => eq(name, true, !!cond);
const group = (t) => console.log(`\n\x1b[1m═══ ${t} ═══\x1b[0m`);

const F = ['موظف واحد', 'موظفان', 'موظفين'];

group('١. العدّ العربي — ثلاثة أعداد لا اثنان');

eq('مفرد بلا رقم',            'موظف واحد', plural(1, F));
eq('⚠️ مثنّى — العربية تملك صيغة له', 'موظفان', plural(2, F));
eq('جمع القلّة ٣',            '3 موظفين', plural(3, F));
eq('وحتى ١٠',                 '10 موظفين', plural(10, F));
eq('⚠️ جمع الكثرة ١١ يعود للمفرد', '11 موظف واحد', plural(11, F));
eq('و٢٥ كذلك',                '25 موظف واحد', plural(25, F));
eq('صفر',                     '0 موظف واحد', plural(0, F));

group('٢. التحية');

eq('الفجر مساء',        'مساء الخير', greeting(new Date(2026, 7, 13, 3)));
eq('الخامسة صباحاً',    'صباح الخير', greeting(new Date(2026, 7, 13, 5)));
eq('الحادية عشرة صباح', 'صباح الخير', greeting(new Date(2026, 7, 13, 11)));
/* ⚠️ العربية لا تعرف «بعد الظهر» تحيةً — «صباح الخير» في الثالثة خطأ */
eq('⚠️ الثانية عشرة ظهراً مساء لا صباح', 'مساء الخير', greeting(new Date(2026, 7, 13, 12)));
eq('والثالثة عصراً مساء', 'مساء الخير', greeting(new Date(2026, 7, 13, 15)));
eq('ومنتصف الليل مساء',   'مساء الخير', greeting(new Date(2026, 7, 13, 0)));

group('٣. الاسم الأول');

eq('الأول وحده',      'ريم', firstName('ريم الأحمد'));
eq('اسم واحد',        'سالم', firstName('سالم'));
eq('مسافات زائدة',    'فهد', firstName('  فهد  العتيبي '));
eq('فارغ لا ينهار',   '', firstName(''));
eq('undefined كذلك',  '', firstName(undefined));

group('٤. الأحرف الأولى');

/* «الأحمد» بعد إسقاط أداة التعريف «أحمد» — فالحرف همزة على ألف لا ألف */
eq('كلمتان',                  'رأ', initials('ريم الأحمد'));
eq('كلمة واحدة',              'س', initials('سالم'));
/* ⚠️ «عبد الله» ← «عب» لا «عا»: أداة التعريف تُسقط من الكلمة الثانية */
eq('⚠️ أداة التعريف تُسقط',    'عل', initials('عبد الله'));
eq('وثلاث كلمات تأخذ اثنتين', 'مع', initials('محمد العتيبي القحطاني'));
eq('فارغ يعطي علامة',         '؟', initials(''));
eq('مسافات فقط',              '؟', initials('   '));

group('٥. لون الصورة الرمزية');

eq('نفس الاسم نفس اللون', hueOf('ريم الأحمد'), hueOf('ريم الأحمد'));
ok('واسمان مختلفان يختلفان', hueOf('ريم الأحمد') !== hueOf('سالم القحطاني'));
ok('ضمن مدى درجة اللون', [...Array(50)].every((_, i) => {
  const h = hueOf('اسم' + i);
  return Number.isInteger(h) && h >= 0 && h < 360;
}));
eq('فارغ لا ينهار', true, Number.isInteger(hueOf('')));

group('٦. اسم اليوم والتاريخ');

ok('يذكر اليوم', /الخميس|الأربعاء|الجمعة|السبت|الأحد|الاثنين|الإثنين|الثلاثاء/
  .test(fmtDayDate(new Date(2026, 7, 13))));
eq('تاريخ باطل لا ينهار', '—', fmtDayDate('ليس تاريخاً'));

console.log(`\n\x1b[1m═══ النتيجة: ${pass} ناجح، ${fail} فاشل ═══\x1b[0m`);
process.exit(fail ? 1 : 0);
