/* ═══════════════════════════════════════════════════════════════════════════
   النوافذ الزمنية للطلبات — الاستئذان والتصحيح

   ⚠️ لماذا وحدة منفصلة: هذه دوال صافية بلا حالة، لكنها كانت تعيش في
   requests.js التي تستورد firebase.js — فتجلب SDK من gstatic وتُنشئ تطبيقاً
   حقيقياً وقت الاستيراد، فلا تُختبر في node. وكان الحل السابق **إعادة كتابة
   الدوال داخل ملف الاختبار**، وتعليقُه يدّعي أن تغييرها في المصدر يُسقط
   الاختبار — وهذا غير صحيح: النسختان مستقلّتان، فتغيير الحدّ في المصدر يمرّ
   والاختبار يحرس رقماً لم يعد مستعملاً.

   الآن الملفان يستوردان هذه الوحدة نفسها، فالحدّ واحد فعلاً.

   ⚠️ وكل حدّ هنا مكرَّر في firestore.rules (permOk / fixOk). الجدار الحقيقي
   هناك، وهذه الوحدة تعطي الرسالة المفهومة قبل أن يصطدم بها المستخدم. أي
   تغيير هنا يتغيّر هناك، وإلا رُفض الطلب برسالة صلاحيات غامضة.

   ⚠️ والمقارنة بنصوص 'YYYY-MM-DD' لا بالطوابع الزمنية: نصوص التواريخ ترتّب
   معجمياً فتُقارن مباشرة، وحساب الفروق بالطوابع يُدخل ساعة اليوم في المقارنة
   فتنقص النافذة يوماً كاملاً قرب منتصف الليل.
   ═══════════════════════════════════════════════════════════════════════════ */

const ymdOf = (d) => d.getFullYear() + '-' +
  String(d.getMonth() + 1).padStart(2, '0') + '-' +
  String(d.getDate()).padStart(2, '0');

const backDate = (todayYmd, days) => {
  const d = new Date(todayYmd + 'T00:00:00');
  if (isNaN(d)) return todayYmd;
  d.setDate(d.getDate() - days);
  return ymdOf(d);
};

/* ═══ الاستئذان ═══
   قرار المالك: يُقدَّم عن يومه أو عن ثلاثة أيام مضت. بعدها يُعتمد التأخير
   «بدون عذر» ويبقى في الخصم.

   ⚠️ الحدّ موجود لأن الاستئذان المعتمد يمحو دقائق التأخير من المسير: بلا
   نافذة يقدر الموظف — بعد أن يرى الخصم — أن يقدّم استئذاناً عن يوم في أول
   الشهر فيلغيه بأثر رجعي. */
export const PERM_BACKDATE_DAYS = 3;
export const permOldestDate = (today) => backDate(today, PERM_BACKDATE_DAYS);
export const permWindowOpen = (dateStr, today) =>
  !!dateStr && dateStr >= permOldestDate(today);

/* ═══ تصحيح البصمة ═══
   سبعة أيام لا ثلاثة، والفرق مقصود: الاستئذان يمحو تأخيراً يعرفه الموظف
   يومه، والتصحيح يضيف بصمة ناقصة لا يكتشفها غالباً إلا حين يرى «نسيان
   بصمة» في صفحة أدائه بعد أيام. */
export const FIX_WINDOW_DAYS = 7;
export const fixOldestDate = (today) => backDate(today, FIX_WINDOW_DAYS);

/* ⚠️ المستقبل مرفوض صراحةً: تصحيح ليوم لم يأتِ بعد ليس تصحيحاً. */
export const fixWindowOpen = (dateStr, today) =>
  !!dateStr && dateStr >= fixOldestDate(today) && dateStr <= today;

/* ═══ السقف الشهري ═══
   ⚠️⚠️ مفروض في الواجهة **وحدها**، ولا يمكن فرضه في قاعدة: عدّ طلبات
   الموظف الأخرى يحتاج استعلاماً داخل القاعدة وFirestore لا يقدر عليه. فلا
   يُقرأ على أنه ضمان من السيرفر — من يتجاوزه بأدوات المطوّر يقدّم طلباً
   رابعاً، لكنه يظهر لمن سيعتمده والعدّاد معروض في تحليلات الموارد البشرية.

   ولماذا سقف أصلاً: بلا حدّ يصير التصحيح باباً خلفياً يُلغي معنى البصمة. */
export const FIX_MAX_PER_CYCLE = 3;

/* ⚠️ المرفوض لا يُحسب: طلب رُفض لم يستهلك شيئاً، وعدّه يعاقب الموظف مرتين
   — مرةً بالرفض ومرةً بحرمانه من محاولة. */
export function fixCountInCycle(requests, uid, cyc) {
  const from = ymdOf(cyc.start), to = ymdOf(cyc.end);
  return (requests || []).filter((r) =>
    r.type === 'attendanceFix' && r.employeeUid === uid &&
    r.status !== 'rejected' && r.date >= from && r.date <= to).length;
}
